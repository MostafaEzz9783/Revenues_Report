export function getBranchPrefix(unitName) {
  const raw = String(unitName || "").trim();
  const match = raw.match(/^(\d{1,2})-/);
  if (!match) return null;
  return match[1].padStart(2, "0");
}

export function enrichUnitWithBranch(row, language = "ar") {
  const unitName = row["اسم الوحدة"] || row.unitName || row.unit || row.unitId || "";
  const prefix = getBranchPrefix(unitName);
  const branchInfo = branchDistrictMap[prefix] || branchDistrictMap[String(Number(prefix))];

  return {
    ...row,
    unitCode: unitName,
    unitId: unitName,
    branchCode: prefix,
    branchName: branchInfo
      ? language === "en"
        ? branchInfo.branchEn
        : branchInfo.branchAr
      : "غير محدد",
    branch: branchInfo
      ? language === "en"
        ? branchInfo.branchEn
        : branchInfo.branchAr
      : "غير محدد",
    districtName: branchInfo
      ? language === "en"
        ? branchInfo.districtEn
        : branchInfo.districtAr
      : "غير محدد",
    district: branchInfo
      ? language === "en"
        ? branchInfo.districtEn
        : branchInfo.districtAr
      : "غير محدد"
  };
}

